#!/usr/bin/env node
// Writes apps/web/src/ui/templates/asf/REGISTRY.md from registry.json, so the human page and the
// data never drift. Run it after every change to registry.json:
//   node apps/web/scripts/asf/registry-md.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "../../src/ui/templates/asf");

export function renderRegistry(registry) {
  const shot = (s) => `[${s.replace(/^public\//, "")}](design/screens/${s})`;
  const row = (p) => `| ${p.name} | ${p.set} | ${p.status} | ${p.screens.map(shot).join("<br>") || "—"} | ${p.notes || ""} |`;
  const count = (set) => registry.pieces.filter((p) => p.set === set).length;
  return [
    "# asf component registry",
    "",
    "<!-- Generated by apps/web/scripts/asf/registry-md.mjs from registry.json; edit the JSON, then rerun the script. -->",
    "",
    `What the asf template covers, which reference screen each piece was drawn from, and what is still missing. Updated ${registry.updated}.`,
    "",
    `When the reference design changes, compare the new screens with the ones listed here, then implement only the pieces whose screens changed and the entries under "Not built yet". Sources: ${registry.sources.admin}; ${registry.sources.public}.`,
    "",
    `## Pieces (${count("core")} core, ${count("extended")} extended)`,
    "",
    "| Piece | Set | Status | Reference | Notes |",
    "|---|---|---|---|---|",
    ...registry.pieces.map(row),
    "",
    "## Foundations",
    "",
    "| Part | Files | Notes |",
    "|---|---|---|",
    ...registry.foundations.map((f) => `| ${f.name} | ${f.files.map((x) => `\`${x}\``).join("<br>")} | ${f.notes} |`),
    "",
    "## Not built yet",
    "",
    "| Piece | Reference | Notes |",
    "|---|---|---|",
    ...registry.planned.map((p) => `| ${p.name} | ${p.screens.map(shot).join("<br>")} | ${p.notes} |`),
    "",
  ].join("\n");
}

// run as a script (also on Windows, where the path is not a file URL)
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const registry = JSON.parse(readFileSync(path.join(dir, "registry.json"), "utf8"));
  writeFileSync(path.join(dir, "REGISTRY.md"), renderRegistry(registry));
  process.stdout.write("wrote REGISTRY.md\n");
}

// pnpm --filter @css/api locations:convert <owner-json>: converts the owner's locations file
// (bangladesh-admin.json) into docs/source/data/bd-locations.csv (keeping existing codes) and
// writes the list of automatic fixes to docs/source/data/corrections.md. No database access.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { convertOwnerLocations, locationsToCsv } from '../src/locations/convert';
import { stripBom } from '../src/locations/csv';

const source = process.argv[2];
if (!source) {
  console.error('usage: locations:convert <path to the owner JSON file>');
  process.exit(1);
}
const dataDir = join(__dirname, '../../../docs/source/data');
const csvPath = join(dataDir, 'bd-locations.csv');
const previous = existsSync(csvPath) ? readFileSync(csvPath, 'utf8') : undefined;
const { rows, fixes } = convertOwnerLocations(
  JSON.parse(stripBom(readFileSync(source, 'utf8'))),
  previous,
);
writeFileSync(csvPath, locationsToCsv(rows));
writeFileSync(
  join(dataDir, 'corrections.md'),
  `# Automatic corrections of the locations data\n\nGenerated by \`pnpm --filter @css/api locations:convert\` from the owner's file. Only mechanical fixes and the places the file leaves without a post code of their own are listed here; content corrections are the owner's.\n\n${fixes.map((f) => `- ${f}`).join('\n')}\n`,
);
console.warn(
  `${rows.length} union-level rows written to bd-locations.csv; ${fixes.length} automatic fixes listed in corrections.md`,
);

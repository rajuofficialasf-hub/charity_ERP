import { effectiveAccess } from '../../../src/access/effective';
import type { AccessRegistry } from '../../../src/access/registry';
import type { RegisteredOperation } from '../../../src/openapi/registry';

/**
 * The expected decision of the authorization matrix (docs/security/RBAC.md, "permissions.yaml
 * schema and loading" and "Server-side enforcement"): `public` passes everyone,
 * `authenticated` every signed-in user, `entity` too (the file service decides per file from the
 * linked record; covered by registration-photos.test.ts), `workflow` too (the
 * application service decides per application and action from the workflow definition; covered by
 * applications.test.ts, application-cycle.test.ts and bulk-review.test.ts), and a permission the
 * users whose role holds it by default
 * (the effective grants of an account with only that role and no project assignment). A route
 * whose entity filters no data (none, global, system) needs the permission at GLOBAL without a
 * condition. The scope dimension (which records) is covered by the scope and IDOR tests.
 */
export const ANONYMOUS = 'anonymous';
const UNFILTERED = new Set(['none', 'global', 'system']);
const NOW = new Date('2026-10-12T00:00:00Z');

export function expectedAllowed(
  registry: AccessRegistry,
  op: Pick<RegisteredOperation, 'permission' | 'scope'>,
  role: string,
): boolean {
  if (op.permission === 'public') return true;
  if (role === ANONYMOUS) return false;
  if (['authenticated', 'entity', 'workflow'].includes(op.permission)) return true;
  const { grants } = effectiveAccess(
    registry,
    {
      roles: [role],
      volunteerType: null,
      projectStaff: [],
      projectVolunteers: [],
      teamProjects: [],
      overrides: [],
    },
    NOW,
  );
  const held = grants.filter((g) => g.permission === op.permission);
  if (UNFILTERED.has(op.scope))
    return held.some((g) => g.scopeType === 'GLOBAL' && g.condition === null);
  return held.length > 0;
}

/** Access-layer refusals; any other answer (2xx, 404, 409, 422, …) passed the access layer. */
export function deniedByAccessLayer(status: number, code: string | undefined): boolean {
  if (status === 401)
    return ['auth.token_missing', 'auth.session_revoked', 'auth.token_stale'].includes(code ?? '');
  return status === 403 && code === 'permission.denied';
}

/** A Markdown report: endpoint × role with ✓ (allowed) and ✗ (denied), plus unused permissions. */
export function matrixReport(
  registry: AccessRegistry,
  rows: { op: RegisteredOperation; decisions: Record<string, boolean> }[],
  roles: string[],
): string {
  const head = [ANONYMOUS, ...roles];
  const short = (r: string) => (r === ANONYMOUS ? 'anon' : r);
  const used = new Set(rows.map((r) => r.op.permission));
  const unused = [...registry.permissions.keys()].filter((p) => !used.has(p)).sort();
  const lines = [
    '# Authorization matrix',
    '',
    'Generated by `apps/api/test/integration/authorization-matrix.test.ts` (the authorization matrix of',
    '`docs/plans/2026-10-12-1100-feat-rbac-permission-panel-plan.md`); do not edit by hand.',
    'Regenerate with `pnpm --filter @css/api authz:matrix` after a route or `permissions.yaml` changes.',
    '',
    'Every registered endpoint was called by an account of every role and by an anonymous caller,',
    'with nonexistent ids and an empty body, so the access layer decides before any handler runs.',
    '✓ means the access layer let the call through (the answer may still be 404 or 422 for the',
    'nonexistent record or the empty body); ✗ means 401 or 403 from the access layer. Every cell',
    'equals the decision `permissions.yaml` defines for the role (role defaults; GLOBAL roles hold',
    'every permission except `global_roles_excluded`). Which records a role reaches inside an',
    'allowed endpoint is decided by the data scope and is tested separately (scope and IDOR tests).',
    '',
    `| Endpoint | Permission | Entity | ${head.map(short).join(' | ')} |`,
    `|---|---|---|${head.map(() => ':-:').join('|')}|`,
    ...rows.map(
      ({ op, decisions }) =>
        `| ${op.method.toUpperCase()} ${op.path} | ${op.permission} | ${op.scope} | ${head
          .map((r) => (decisions[r] ? '✓' : '✗'))
          .join(' | ')} |`,
    ),
    '',
    `## Permissions no endpoint uses yet (${unused.length})`,
    '',
    'They belong to features of later tasks; the matrix covers them when their endpoints exist.',
    '',
    ...unused.map((p) => `- \`${p}\``),
    '',
  ];
  return lines.join('\n');
}
